  await expect(primary).toContainText('Deploy')
  await edit(page, 'import { take, put } from "inherit"\nfunction smelt() { take("mine"); put("furnace") }\nfunction ship() { take("furnace"); put("cart") }\nexport function onTick() { smelt(); ship() }')
